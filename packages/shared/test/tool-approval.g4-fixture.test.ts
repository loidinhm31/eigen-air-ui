import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import {
  decodeToolApprovalEvent,
  decodeToolApprovalSnapshot,
  ToolApprovalDecodeError,
} from "../src/types/tool-approval-decoder.js";
import { decodeWsFrameJson } from "../src/types/user-question-decoder.js";
import type { ToolApprovalTerminalCode } from "../src/types/tool-approval.js";

function resolveBackendRoot(): string {
  if (process.env.EIGEN_AIR_DIR) {
    return resolve(process.env.EIGEN_AIR_DIR);
  }
  const testDir =
    typeof __dirname !== "undefined"
      ? __dirname
      : fileURLToPath(new URL(".", import.meta.url));
  const candidateDirect = [
    resolve(testDir, "../../../eigen-air"),
    resolve(testDir, "../../../../../eigen-air"),
    resolve(process.cwd(), "../../../eigen-air"),
  ];
  for (const c of candidateDirect) {
    if (existsSync(join(c, "Cargo.toml"))) return c;
  }
  const searchRoots = [
    resolve(testDir, "../../../../../.."),
    resolve(process.cwd(), "../../.."),
  ];
  for (const root of searchRoots) {
    if (existsSync(root)) {
      try {
        const entries = readdirSync(root, { withFileTypes: true });
        for (const entry of entries) {
          if (entry.isDirectory()) {
            const manifest = join(root, entry.name, "Cargo.toml");
            if (existsSync(manifest)) {
              const content = readFileSync(manifest, "utf8");
              if (content.includes('name = "eigen-air"')) {
                return join(root, entry.name);
              }
            }
          }
        }
      } catch {}
    }
  }
  return resolve(testDir, "../../../eigen-air");
}

const backendRoot = resolveBackendRoot();
const fixturePath = join(backendRoot, "test-fixtures/contracts/g4-tool-approval-v1.json");
const fixtureBytes = readFileSync(fixturePath);
const fixture = JSON.parse(fixtureBytes.toString("utf8")) as {
  schema: string;
  version: string;
  states: string[];
  terminal_states: string[];
  safe_codes: string[];
  sample_pending_snapshots: unknown[];
  sample_events: unknown[];
  negative_outcome_vectors: Array<{
    code: string;
    synthetic_tool_result: string;
    has_live_capsule: boolean;
    next_action: string;
    skip_remaining_calls: boolean;
  }>;
  redaction_assertion: {
    policy: string;
    forbidden_keys: string[];
  };
};

describe("Rust-generated G4 tool-approval fixture handoff", () => {
  it("pins the backend-generated bytes without copying them into the sibling", () => {
    const hash = createHash("sha256").update(fixtureBytes).digest("hex");
    expect(hash).toBe("10fd1eea59fe5bf4dbb8257248b57b6557658b47d485cdf9e1c4698f10054784");
    expect(fixture.schema).toBe("eigen-air.g4.tool-approval-v1");
    expect(fixture.version).toBe("tool_approval.v1");
  });

  it("decodes every generated sample pending snapshot", () => {
    expect(fixture.sample_pending_snapshots.length).toBeGreaterThan(0);
    for (const rawSnapshot of fixture.sample_pending_snapshots) {
      const decoded = decodeToolApprovalSnapshot(rawSnapshot);
      expect(decoded.state).toBe("pending");
      expect(decoded.schema_version).toBe("tool_approval.v1");
      expect(decoded.risk).toBe("high");
      expect(decoded.redaction).toBe("metadata_only");
      expect(decoded.binding_digest).toMatch(/^[0-9a-f]{64}$/);
      expect(decoded.safe_summary).toBeDefined();
    }
  });

  it("decodes every generated sample event and parses via decodeWsFrameJson", () => {
    expect(fixture.sample_events.length).toBeGreaterThan(0);
    for (const rawEvent of fixture.sample_events) {
      const decoded = decodeToolApprovalEvent(rawEvent);
      expect(decoded.event).toBe("tool_approval.updated");
      expect(decoded.payload.redaction).toBe("metadata_only");
      expect(decoded.payload.state).toBe("pending");

      const frame = decodeWsFrameJson(JSON.stringify(rawEvent));
      expect(frame).toBeDefined();
      if (frame && frame.type === "event") {
        expect(frame.event).toBe("tool_approval.updated");
      }
    }
  });

  it("rejects forbidden redaction keys when injected into snapshots", () => {
    const baseSnapshot = fixture.sample_pending_snapshots[0] as Record<string, unknown>;
    for (const forbiddenKey of fixture.redaction_assertion.forbidden_keys) {
      const hostile = {
        ...baseSnapshot,
        [forbiddenKey]: "leaked_secret_or_raw_data",
      };
      expect(() => decodeToolApprovalSnapshot(hostile)).toThrow(ToolApprovalDecodeError);
    }
  });

  it("rejects private or extra fields in sample snapshots", () => {
    const baseSnapshot = fixture.sample_pending_snapshots[0] as Record<string, unknown>;
    const withPrivate = {
      ...baseSnapshot,
      lease_owner: "daemon-worker-1",
    };
    expect(() => decodeToolApprovalSnapshot(withPrivate)).toThrow(ToolApprovalDecodeError);
  });

  it("validates that all safe_codes from the fixture are known terminal codes", () => {
    const expectedSafeCodes: ToolApprovalTerminalCode[] = [
      "approval_denied",
      "approval_expired",
      "approval_cancelled",
      "approval_binding_drift",
      "approval_policy_drift",
      "approval_safe_summary_unavailable",
      "approval_resolver_unavailable",
      "approval_store_mismatch",
      "approval_config_mismatch",
      "approval_backend_unsupported",
      "approval_conflict",
      "approval_indeterminate",
    ];
    for (const code of fixture.safe_codes) {
      expect(expectedSafeCodes).toContain(code as ToolApprovalTerminalCode);
    }
  });
});
